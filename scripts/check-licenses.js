const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const NEW_ROOTS = ['@langchain/langgraph', 'ws'];

function readLock() {
  return JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
}

function licenseOf(entry, key) {
  if (entry && entry.license) {
    if (typeof entry.license === 'string') return entry.license;
    if (entry.license.type) return entry.license.type;
  }
  const file = path.join(root, key, 'package.json');
  if (fs.existsSync(file)) {
    const pkg = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (typeof pkg.license === 'string') return pkg.license;
    if (pkg.license && pkg.license.type) return pkg.license.type;
  }
  return 'UNKNOWN';
}

function isCopyleft(license) {
  const text = String(license || '').replace(/LGPL/gi, '');
  return /\bAGPL\b|\bGPL\b/i.test(text);
}

function resolveDep(packages, fromKey, name) {
  const segments = fromKey.split('/');
  for (let i = segments.length; i >= 1; i -= 1) {
    const candidate = [...segments.slice(0, i), 'node_modules', name].join('/');
    if (packages[candidate]) return candidate;
  }
  const top = `node_modules/${name}`;
  return packages[top] ? top : null;
}

function walk(packages, name) {
  const start = `node_modules/${name}`;
  const seen = new Set();
  const ordered = [];
  function visit(key) {
    if (!key || seen.has(key) || !packages[key]) return;
    seen.add(key);
    const entry = packages[key];
    ordered.push({
      name: key.replace(/^node_modules\//, ''),
      version: entry.version || '',
      license: licenseOf(entry, key),
    });
    const deps = {
      ...(entry.dependencies || {}),
      ...(entry.optionalDependencies || {}),
      ...(entry.peerDependencies || {}),
    };
    for (const depName of Object.keys(deps)) visit(resolveDep(packages, key, depName));
  }
  visit(start);
  return ordered;
}

function buildReport(lock = readLock()) {
  const packages = lock.packages || {};
  const trees = NEW_ROOTS.map((name) => ({ name, packages: walk(packages, name) }));
  const flat = [];
  const seen = new Set();
  for (const tree of trees) {
    for (const pkg of tree.packages) {
      if (seen.has(pkg.name)) continue;
      seen.add(pkg.name);
      flat.push(pkg);
    }
  }
  const all = Object.entries(packages)
    .filter(([key]) => key.startsWith('node_modules/'))
    .map(([key, entry]) => ({
      name: key.replace(/^node_modules\//, ''),
      version: entry.version || '',
      license: licenseOf(entry, key),
    }));
  return {
    trees,
    packages: flat,
    copyleft: flat.filter((pkg) => isCopyleft(pkg.license)),
    productionCopyleft: all.filter((pkg) => isCopyleft(pkg.license)),
  };
}

function render(report) {
  const lines = [
    '# Third-party notices',
    '',
    'Gitgram is MIT licensed. This file lists the dependencies added for the team dashboard (`@langchain/langgraph` and `ws`) and the packages they pull in. It was generated by `node scripts/check-licenses.js`, which reads `package-lock.json` and each package `license` field.',
    '',
    'Voice recordings are not a dependency concern: raw audio is transcribed in memory and discarded unless `TEAM_RETAIN_VOICE=1`.',
    '',
  ];
  if (report.copyleft.length || report.productionCopyleft.length) {
    lines.push('## GPL / AGPL', '');
    lines.push('The license checker found copyleft packages. Review them before shipping:', '');
    for (const pkg of report.productionCopyleft) {
      lines.push(`- ${pkg.name}@${pkg.version} — ${pkg.license}`);
    }
    lines.push('');
  } else {
    lines.push('## GPL / AGPL', '');
    lines.push('No GPL or AGPL packages were found in the new dependency tree or in the rest of the installed production tree. LGPL names are not treated as GPL.', '');
  }
  for (const tree of report.trees) {
    lines.push(`## ${tree.name}`, '');
    lines.push('| Package | Version | License |');
    lines.push('| --- | --- | --- |');
    for (const pkg of tree.packages) {
      lines.push(`| ${pkg.name} | ${pkg.version} | ${pkg.license} |`);
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

if (require.main === module) {
  const report = buildReport();
  fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), render(report));
  const found = report.productionCopyleft.length;
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${report.packages.length} packages in the new trees, ${found} GPL/AGPL).`);
  if (found) process.exitCode = 1;
}

module.exports = { buildReport, render, isCopyleft };
